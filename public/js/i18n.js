function t(key) { return (i18n[currentLang] || i18n.es)[key] || key; }

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.getElementById('langEs').classList.toggle('active', lang === 'es');
  document.getElementById('langEn').classList.toggle('active', lang === 'en');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[lang][key]) el.innerHTML = i18n[lang][key];
  });
  document.querySelectorAll('[data-i18n-icon]').forEach(el => {
    const key = el.dataset.i18nIcon;
    const text = i18n[lang][key];
    if (text) el.textContent = text.charAt(0).toUpperCase();
  });
  if (typeof renderReview === 'function' && document.getElementById('panel3').classList.contains('active')) {
    renderReview();
  } else if (extractedOps.length) {
    renderOps();
  }
  if (selectedLevel > 1) selectLevel(selectedLevel);
  if (lastResults) renderResults(lastResults);
  localStorage.setItem('gaiax-lang', lang);
}
